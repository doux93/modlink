#!/usr/bin/env python3
"""Generate a deterministic coverage report from committed knowledge data."""

import argparse
import json
from collections import Counter
from pathlib import Path

try:
    import yaml
except ImportError as exc:
    raise SystemExit("PyYAML is required: pip install pyyaml") from exc


def load_yaml_files(path: Path) -> list[dict]:
    return [
        yaml.safe_load(file.read_text(encoding="utf-8"))
        for file in sorted(path.glob("*.yaml"))
    ]


def load_profiles(path: Path) -> list[dict]:
    profiles = []
    for data in load_yaml_files(path):
        if data.get("schema") != "modulink/profile-catalog@1":
            profiles.append(data)
            continue
        defaults = data.get("defaults", {})
        for entry in data.get("profiles", []):
            profiles.append({**defaults, **entry})
    return profiles


def topic_metadata(index_file: Path) -> list[dict]:
    return [
        json.loads(line)
        for line in index_file.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]


def unique_topic_models(topics: list[dict]) -> dict[str, set[str]]:
    """Return normalized model scopes keyed by canonical topic identity."""
    result: dict[str, set[str]] = {}
    for offset, topic in enumerate(topics):
        topic_id = str(topic.get("topic_id") or topic.get("content_hash") or f"row:{offset}")
        models = result.setdefault(topic_id, set())
        models.update(
            str(model).strip().upper()
            for model in topic.get("models", [])
            if str(model).strip()
        )
    return result


def profile_topic_counts(
    topic_models: dict[str, set[str]], profile: dict
) -> tuple[int, int]:
    """Count unique exact and same-series topics without double counting."""
    exact_models = {
        str(model).strip().upper()
        for model in profile.get("model_codes", [])
        if str(model).strip()
    }
    series = str(profile.get("series", "")).strip().upper()
    if series == "GENERIC":
        series = ""

    exact = 0
    same_series = 0
    for models in topic_models.values():
        if models & exact_models:
            exact += 1
        elif series and any(model == series or model.startswith(series) for model in models):
            same_series += 1
    return exact, same_series


def inherited_models(at_file: dict, command: dict) -> list[str]:
    models = command.get("models") or []
    if models:
        return models
    applies_to = at_file.get("applies_to")
    return applies_to if isinstance(applies_to, list) else []


def coverage_owner(model: str, profiles: list[dict]) -> tuple[str, str]:
    for profile in profiles:
        if model in profile.get("model_codes", []):
            support = profile.get("support_level", "unspecified")
            return ("exact" if support == "verified" else support), profile["id"]
    for profile in profiles:
        series = profile.get("series", "").upper()
        if series and series != "GENERIC" and (model == series or model.startswith(series)):
            return "series", profile["id"]
    return "uncovered", "-"


def generate(data_dir: Path) -> str:
    profiles = load_profiles(data_dir / "profiles")
    at_files = load_yaml_files(data_dir / "at_docs")
    # Coverage is intentionally derived from the committed public index only.
    topics = topic_metadata(data_dir / "kb_index" / "manual_topics_public.jsonl")
    topic_models = unique_topic_models(topics)
    model_topics = Counter(
        model
        for models in topic_models.values()
        for model in models
    )
    unknown_topics = sum(not models for models in topic_models.values())
    model_scoped_topics = len(topic_models) - unknown_topics
    manuals = {topic.get("manual", "") for topic in topics if topic.get("manual")}
    repositories = {
        str(owner.get("map_id", "")).replace("\\", "/").split("/", 1)[0]
        for topic in topics
        for owner in topic.get("owners", [])
        if owner.get("map_id")
    }

    commands = [
        (at_file, command)
        for at_file in at_files
        for command in at_file.get("commands", [])
    ]
    unique_commands = {command["cmd"] for _, command in commands}
    scoped_commands = sum(bool(inherited_models(at_file, command)) for at_file, command in commands)
    source_links = sum(
        len(command.get("sources") or ([command["source"]] if command.get("source") else []))
        for _, command in commands
    )

    support_counts = Counter(profile.get("support_level", "unspecified") for profile in profiles)
    lines = [
        "# Knowledge Base Coverage",
        "",
        "Generated by `python tools/kb_coverage.py`. Do not edit counts manually.",
        "",
        "## Summary",
        "",
        f"- Profiles: {len(profiles)} ({support_counts['verified']} verified, "
        f"{support_counts['reference']} reference, {support_counts['generic']} generic/fallback)",
        f"- Manual repositories: {len(repositories)}",
        f"- Manual titles: {len(manuals)}",
        f"- Indexed topics: {len(topic_models)} ({model_scoped_topics} model-scoped topics, "
        f"{unknown_topics} unknown topics)",
        f"- Discovered model codes: {len(model_topics)}",
        f"- AT document entries: {len(commands)} ({len(unique_commands)} unique commands, "
        f"{scoped_commands} model-scoped entries)",
        f"- Preserved AT source links: {source_links}",
        "",
        "## Supported Profiles",
        "",
        "| Profile | Models | Series | Support | Capabilities | Built-in AT | Exact topics | Series topics |",
        "| --- | --- | --- | --- | --- | ---: | ---: | ---: |",
    ]

    support_order = {"verified": 0, "reference": 1, "generic": 2}
    for profile in sorted(
        profiles,
        key=lambda item: (support_order.get(item.get("support_level"), 3), item["name"]),
    ):
        models = [model.upper() for model in profile.get("model_codes", [])]
        series = profile.get("series", "").upper()
        exact_topics, series_topics = profile_topic_counts(topic_models, profile)
        lines.append(
            f"| {profile['id']} | {', '.join(models) or '-'} | {series or '-'} | "
            f"{profile.get('support_level', 'unspecified')} | "
            f"{', '.join(profile.get('capabilities', [])) or '-'} | "
            f"{len(profile.get('at_commands', []))} | {exact_topics} | {series_topics} |"
        )

    lines.extend([
        "",
        "## Discovered Models",
        "",
        "`reference` means the model has exact offline manuals but its built-in command set has not been device-verified.",
        "",
        "| Model | Topics | Coverage | Profile |",
        "| --- | ---: | --- | --- |",
    ])
    for model, count in sorted(model_topics.items()):
        status, owner = coverage_owner(model, profiles)
        lines.append(f"| {model} | {count} | {status} | {owner} |")

    lines.extend([
        "",
        "## Interpretation",
        "",
        "- `exact` profiles have device-verified built-in behavior; `reference` profiles have exact-model offline manuals.",
        "- Same-series manuals are searchable but are labeled as series references.",
        "- Generic or unknown profiles never receive model-scoped documents.",
        "- A new profile should be added only after detection rules and command differences are validated.",
        "",
    ])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", default="data")
    parser.add_argument("--output", default="docs/kb-coverage.md")
    args = parser.parse_args()

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    with open(output, "w", encoding="utf-8", newline="\n") as file:
        file.write(generate(Path(args.data)))
    print(f"wrote {output}")


if __name__ == "__main__":
    main()
